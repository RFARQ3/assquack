"""Produce auditable timing tables from the saved serial NDJSON trials."""

import json
from collections import defaultdict
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "benchmarks/results/ndjson-2026-10-28.jsonl"
DESTINATION = ROOT / "docs/research/2026-10-28-ndjson-timing-tables.md"


def main():
    groups = defaultdict(list)
    for line in SOURCE.read_text().splitlines():
        row = json.loads(line)
        key = tuple(
            row[k]
            for k in [
                "rows",
                "shape",
                "kind",
                "writer",
                "sizing",
                "calibration_target_bytes",
            ]
        )
        groups[key].append(row)
    lines = [
        "# NDJSON measured timing tables",
        "",
        "Generated by `benchmarks/summarize_ndjson.py` from the durable raw trials.",
        "See [methodology and recommendation](2026-10-28-ndjson-diagnostics.md).",
        "",
        "Times are seconds; W/R/T are median write/read/combined. Range is the",
        "minimum-maximum combined time. RSS is maximum sampled absolute process",
        "RSS / maximum incremental phase RSS, in decimal MB; it includes native",
        "allocations. File sizes are min/median/max across all repetitions, in MB.",
        "The target column shows MB for byte policies and rows for row policies.",
        "All rows below passed exhaustive value and expected-type checks.",
        "",
    ]
    previous = None
    for key, rows in sorted(groups.items()):
        n, shape, kind, writer, sizing, target = key
        section = (n, shape, kind)
        if section != previous:
            lines += [
                "",
                f"## {kind}, {shape}, {n:,} rows",
                "",
                "| Writer / sizing | Target | Trials | W | R | T | T range "
                "| RSS MB | Files | File MB min/median/max |",
                "|---|---:|---:|---:|---:|---:|---|---|---:|---|",
            ]
            previous = section
        sizes = [size / 1e6 for row in rows for size in row["file_sizes"]]
        rss = max(max(r["write_peak_rss"], r["read_peak_rss"]) for r in rows) / 1e6
        increment = (
            max(max(r["write_increment_rss"], r["read_increment_rss"]) for r in rows)
            / 1e6
        )
        limit = (
            str(rows[0]["row_limit"]) if sizing == "rows" else str(target // 1_000_000)
        )
        lines.append(
            f"| {writer} / {sizing} | {limit} | {len(rows)} | "
            f"{median(r['write_s'] for r in rows):.3f} | "
            f"{median(r['read_s'] for r in rows):.3f} | "
            f"{median(r['combined_s'] for r in rows):.3f} | "
            f"{min(r['combined_s'] for r in rows):.3f}-"
            f"{max(r['combined_s'] for r in rows):.3f} | "
            f"{rss:.0f} / {increment:.0f} | {len(rows[0]['file_sizes'])} | "
            f"{min(sizes):.3f}/{median(sizes):.3f}/{max(sizes):.3f} |"
        )
    DESTINATION.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"{sum(map(len, groups.values()))} measured trials, "
        f"{len(groups)} configurations"
    )


if __name__ == "__main__":
    main()
